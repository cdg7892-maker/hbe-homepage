export function getColumnBySlug(slug) {
  return COLUMN_DATA.find((column) => column.slug === slug)
}

export function getRelatedColumns(slug, limit = 3) {
  const current = getColumnBySlug(slug)
  return COLUMN_DATA.filter((column) => column.slug !== slug)
    .sort((a, b) => {
      const categoryScore = Number(b.category === current?.category) - Number(a.category === current?.category)
      return categoryScore
    })
    .slice(0, limit)
}
