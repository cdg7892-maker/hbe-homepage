function withExpandedFaqs(column) {
  const seen = new Set()
  const faqs = [...(column.faqs ?? []), ...getContextualFaqs(column)].filter((faq) => {
    if (seen.has(faq.question)) return false
    seen.add(faq.question)
    return true
  })

  return {
    ...column,
    faqs: faqs.slice(0, 10),
    persuasion: getPersuasionStructure(column),
  }
}

export const COLUMN_DATA = RAW_COLUMN_DATA.map(withExpandedFaqs)

export function getColumnBySlug(slug) {
  return COLUMN_DATA.find((column) => column.slug === slug)
}

export function getRelatedColumns(slug, limit = 3) {
  const current = getColumnBySlug(slug)
  return COLUMN_DATA.filter((column) => column.slug !== slug)
    .sort((a, b) => {
      const categoryScore = Number(b.category === current?.category) - Number(a.category === current?.category)
      return categoryScore
    })
    .slice(0, limit)
}
